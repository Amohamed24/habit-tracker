CREATE TABLE IF NOT EXISTS habits (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL, description varchar(255), frequency varchar(255) NOT NULL,
  user_id bigint NOT NULL, created_at timestamp(6), updated_at timestamp(6));
CREATE TABLE IF NOT EXISTS habit_completions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  habit_id bigint NOT NULL, completion_date date NOT NULL, created_at timestamp(6));
DO $$
BEGIN
  -- guard by definition, not by name: Hibernate-generated names differ on existing volumes
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'habit_completions'::regclass AND contype = 'u'
                 AND pg_get_constraintdef(oid) = 'UNIQUE (habit_id, completion_date)') THEN
    ALTER TABLE habit_completions ADD CONSTRAINT uk_habit_completions_habit_date UNIQUE (habit_id, completion_date);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'habit_completions'::regclass AND contype = 'f'
                 AND pg_get_constraintdef(oid) = 'FOREIGN KEY (habit_id) REFERENCES habits(id)') THEN
    ALTER TABLE habit_completions ADD CONSTRAINT fk_habit_completions_habit FOREIGN KEY (habit_id) REFERENCES habits(id);
  END IF;
END $$;
